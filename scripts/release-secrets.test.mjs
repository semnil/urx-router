// Pins where release.yml lets the signing material go. The `build` job holds the updater
// signing key, the Developer ID certificate, the notarization credentials and a token that
// can write releases; this file holds that only the bundling step receives them, and that
// every step running third-party build code — the frontend build, and the Rust compile with
// its build scripts and procedural macros — runs before it, in a step that holds none.
//
// The rules, each a property of the workflow text:
//   - the workflow-level `permissions` grant nothing beyond read, and only `create-release`
//     and `build` grant `contents: write`;
//   - the `build` job's checkout does not leave the job's token in the git configuration;
//   - the only step in `build` whose environment names a secret is the tauri-action step;
//   - that step passes a `--config` file which empties `build.beforeBuildCommand`, so
//     `tauri build` runs no frontend build inside it;
//   - earlier steps run the frontend build — the same command tauri.conf.json names as
//     `beforeBuildCommand` — and `tauri build --no-bundle` with that same `--config` file,
//     twice: the app's build script writes src-tauri/permissions/autogenerated and watches
//     src-tauri/permissions, so on a fresh checkout the build after the first one reruns it,
//     and the second compile is where that rerun happens rather than the bundling step.
//
// Every rule is also shown the arrangement it refuses, built by mutating the real workflow,
// beside the real workflow it is a mutation of: a rule that only ever sees good input can
// be one that never fires.

import { describe, expect, it } from "vitest";
import { readFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = fileURLToPath(new URL("..", import.meta.url));
const RELEASE = ".github/workflows/release.yml";
const read = (path) => readFileSync(join(ROOT, path), "utf8");
const readJson = (path) => JSON.parse(read(path));

const WRITERS = new Set(["create-release", "build"]);

// --- reading the workflow ----------------------------------------------------------------

const indentOf = (line) => line.search(/\S/);
const value = (line) =>
  line
    .slice(line.indexOf(":") + 1)
    .replace(/\s+#.*$/, "")
    .trim();

// The lines a key at `indent` owns: those after it indented further, up to the first that is not.
function owned(lines, at) {
  const indent = indentOf(lines[at]);
  const out = [];
  for (const line of lines.slice(at + 1)) {
    if (indentOf(line) <= indent) break;
    out.push(line);
  }
  return out;
}

// `key:` at exactly `indent`, as the lines it owns, or null when absent.
function section(lines, key, indent) {
  const at = lines.findIndex((l) => indentOf(l) === indent && l.trim().startsWith(`${key}:`));
  return at < 0 ? null : { line: lines[at], body: owned(lines, at) };
}

function parse(text) {
  // Comment-only and blank lines carry nothing either question reads.
  const lines = text.split("\n").filter((l) => l.trim() !== "" && !/^\s*#/.test(l));
  const jobsAt = lines.findIndex((l) => l === "jobs:");
  const jobs = new Map();
  let name = null;
  for (const line of lines.slice(jobsAt + 1)) {
    const header = /^ {2}([\w-]+):\s*$/.exec(line);
    if (header) jobs.set((name = header[1]), []);
    else if (name) jobs.get(name).push(line);
  }
  return { top: lines.slice(0, jobsAt), jobs };
}

// Each step of a job, with its first line's `- ` turned into indentation so every key of the
// step sits at one column.
function steps(jobLines) {
  const stepsAt = jobLines.findIndex((l) => /^ {4}steps:\s*$/.test(l));
  if (stepsAt < 0) return [];
  const out = [];
  for (const line of owned(jobLines, stepsAt)) {
    if (/^ {6}- /.test(line)) out.push([line.replace(/^( {6})- /, "$1  ")]);
    else out.at(-1)?.push(line);
  }
  return out.map((lines) => {
    const uses = section(lines, "uses", 8);
    const run = section(lines, "run", 8);
    const env = section(lines, "env", 8);
    const withs = section(lines, "with", 8);
    const input = (key) => {
      const hit = withs && section(withs.body, key, 10);
      return hit ? value(hit.line) : null;
    };
    const runText = run ? [value(run.line), ...run.body.map((l) => l.trim())].join("\n").replace(/^[|>]\n/, "") : null;
    return {
      uses: uses ? value(uses.line) : null,
      run: runText,
      secrets: namesSecret(lines),
      input,
    };
  });
}

const namesSecret = (lines) => lines.some((l) => /\bsecrets\./.test(l) || /^\s*secrets:\s*inherit\b/.test(l));
const configOf = (args) => /--config\s+(\S+)/.exec(args ?? "")?.[1] ?? null;
// A `permissions` block grants contents: write through its own line (`write-all`) or a scope under it.
const grantsWrite = (permissions) =>
  !!permissions &&
  (value(permissions.line) === "write-all" || permissions.body.some((l) => /^\s*contents:\s*write\b/.test(l)));

/** Every way `text` (release.yml) lets the signing material reach code other than the
 *  bundling step's. `readConfig` reads a `--config` file the workflow names. */
function exposures(text, readConfig, beforeBuild) {
  const found = [];
  const { top, jobs } = parse(text);

  if (namesSecret(section(top, "env", 0)?.body ?? [])) found.push("the workflow env names a secret");
  const topPermissions = section(top, "permissions", 0);
  if (!topPermissions) found.push("the workflow declares no top-level permissions");
  else if (value(topPermissions.line) === "write-all") found.push("the workflow grants write-all to every job");
  for (const line of topPermissions?.body ?? []) {
    if (value(line) === "write") found.push(`the workflow grants ${line.trim()} to every job`);
  }
  for (const [job, lines] of jobs) {
    if (grantsWrite(section(lines, "permissions", 4)) && !WRITERS.has(job)) {
      found.push(`job ${job} grants contents: write`);
    }
    if (job !== "build" && namesSecret(lines)) found.push(`job ${job} names a secret`);
  }

  const build = jobs.get("build");
  if (!build) return [...found, "no build job"];
  if (namesSecret(section(build, "env", 4)?.body ?? [])) found.push("the build job's env names a secret");
  const all = steps(build);

  const checkout = all.find((s) => s.uses?.startsWith("actions/checkout@"));
  if (checkout?.input("persist-credentials") !== "false") {
    found.push("the build job's checkout leaves the token in the git configuration");
  }

  const bundleAt = all.findIndex((s) => s.uses?.startsWith("tauri-apps/tauri-action@"));
  for (const [i, step] of all.entries()) {
    if (step.secrets && i !== bundleAt) found.push(`build step ${i + 1} (${step.uses ?? step.run}) holds a secret`);
  }
  if (bundleAt < 0) return [...found, "no tauri-action step"];

  const config = configOf(all[bundleAt].input("args"));
  if (!config) found.push("the tauri-action step passes no --config");
  else if (readConfig(config)?.build?.beforeBuildCommand !== "") {
    found.push(`${config} does not empty build.beforeBuildCommand`);
  }

  const earlier = all.slice(0, bundleAt);
  if (!earlier.some((s) => s.run === beforeBuild)) {
    found.push(`no step before tauri-action runs the frontend build (${beforeBuild})`);
  }
  const compiles = earlier.filter((s) => /\btauri build\b/.test(s.run ?? "") && /--no-bundle\b/.test(s.run));
  if (compiles.length === 0) found.push("no step before tauri-action compiles with tauri build --no-bundle");
  else if (compiles.length === 1) found.push("the --no-bundle compile runs once before tauri-action, not twice");
  for (const compile of compiles) {
    if (config && configOf(compile.run) !== config) {
      found.push(`a --no-bundle compile does not pass ${config}, the file the tauri-action step passes`);
    }
  }
  return found;
}

// --- cases -------------------------------------------------------------------------------

const WORKFLOW = read(RELEASE);
const BEFORE_BUILD = readJson("src-tauri/tauri.conf.json").build.beforeBuildCommand;
const check = (text, readConfig = readJson) => exposures(text, readConfig, BEFORE_BUILD);

// A mutation that does not change the text would pass every case below vacuously.
function mutate(text, from, to) {
  const out = text.replace(from, to);
  expect(out, `mutation did not apply: ${from}`).not.toBe(text);
  return out;
}

describe("release.yml keeps the signing material in the bundling step", () => {
  it("holds on the workflow as it stands", () => {
    expect(check(WORKFLOW)).toEqual([]);
  });

  it("refuses a workflow-wide contents: write", () => {
    const text = mutate(WORKFLOW, /^permissions:\n {2}contents: read$/m, "permissions:\n  contents: write");
    expect(check(text)).toContain("the workflow grants contents: write to every job");
  });

  it("refuses contents: write on a job that creates and uploads nothing", () => {
    const text = mutate(WORKFLOW, /^ {2}check-tag:\n/m, "  check-tag:\n    permissions:\n      contents: write\n");
    expect(check(text)).toContain("job check-tag grants contents: write");
    const all = mutate(WORKFLOW, /^ {2}release-gate:\n/m, "  release-gate:\n    permissions: write-all\n");
    expect(check(all)).toContain("job release-gate grants contents: write");
    const top = mutate(WORKFLOW, /^permissions:\n {2}contents: read$/m, "permissions: write-all");
    expect(check(top)).toContain("the workflow grants write-all to every job");
  });

  it("refuses a secret handed to any job but build", () => {
    const text = mutate(
      WORKFLOW,
      /^( {4})uses: \.\/\.github\/workflows\/licenses\.yml\n/m,
      "$1uses: ./.github/workflows/licenses.yml\n$1secrets: inherit\n",
    );
    expect(check(text)).toContain("job licenses names a secret");
  });

  it("refuses a build checkout that persists the token", () => {
    const text = mutate(WORKFLOW, /\n\s*persist-credentials: false/, "");
    expect(check(text)).toContain("the build job's checkout leaves the token in the git configuration");
  });

  it("refuses a secret on a step that runs build code", () => {
    const text = mutate(
      WORKFLOW,
      /^( {6})- run: pnpm build\n/m,
      "$1- run: pnpm build\n$1  env:\n$1    TAURI_SIGNING_PRIVATE_KEY: ${{ secrets.TAURI_SIGNING_PRIVATE_KEY }}\n",
    );
    expect(check(text).some((f) => f.endsWith("(pnpm build) holds a secret"))).toBe(true);
  });

  it("refuses a secret in the build job's own env, which every step receives", () => {
    const text = mutate(
      WORKFLOW,
      /^( {4})timeout-minutes: 60\n {4}steps:\n/m,
      "$1timeout-minutes: 60\n$1env:\n$1  APPLE_PASSWORD: ${{ secrets.MACOS_NOTARIZATION_PASSWORD }}\n$1steps:\n",
    );
    expect(check(text)).toContain("the build job's env names a secret");
  });

  it("refuses a tauri-action step that would run the frontend build itself", () => {
    const noConfig = mutate(WORKFLOW, /(args: )--config \S+ /, "$1");
    expect(check(noConfig)).toContain("the tauri-action step passes no --config");
    const hook = check(WORKFLOW, (path) =>
      path.endsWith(".json") ? { build: { beforeBuildCommand: "pnpm build" } } : null,
    );
    expect(hook.some((f) => f.endsWith("does not empty build.beforeBuildCommand"))).toBe(true);
  });

  it("refuses a bundling step whose compile has not already run, twice", () => {
    const step = /^ {6}- run: pnpm tauri build --no-bundle .*\n(?: {8}.*\n)*/m;
    const once = mutate(WORKFLOW, step, "");
    expect(check(once)).toContain("the --no-bundle compile runs once before tauri-action, not twice");
    const never = mutate(once, step, "");
    expect(check(never)).toContain("no step before tauri-action compiles with tauri build --no-bundle");
    const otherConfig = mutate(
      WORKFLOW,
      /(- run: pnpm tauri build --no-bundle --config )\S+/,
      "$1src-tauri/other.conf.json",
    );
    expect(check(otherConfig).some((f) => f.startsWith("a --no-bundle compile does not pass"))).toBe(true);
  });

  it("refuses a frontend build that is missing or differs from tauri.conf.json's", () => {
    const text = mutate(WORKFLOW, /^( {6})- run: pnpm build\n/m, "$1- run: pnpm build:demo\n");
    expect(check(text)).toContain(`no step before tauri-action runs the frontend build (${BEFORE_BUILD})`);
  });
});
